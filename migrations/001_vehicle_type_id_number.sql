-- One-time Oracle 19c migration for an existing schema.
-- Preserves all VEHICLE_TYPE and VEHICLE rows while changing the parent key
-- and child foreign key from VARCHAR2 to generated numeric IDs.
-- Run once in SQL Developer as a script. Do not run against a fresh schema.

ALTER TABLE VEHICLE DROP CONSTRAINT FK_VEHICLE_TYPE;

ALTER TABLE VEHICLE_TYPE ADD (
    VEHICLE_TYPE_ID_NUM NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY
);

ALTER TABLE VEHICLE ADD (
    VEHICLE_TYPE_ID_NUM NUMBER(10)
);

UPDATE VEHICLE V
SET VEHICLE_TYPE_ID_NUM = (
    SELECT VT.VEHICLE_TYPE_ID_NUM
    FROM VEHICLE_TYPE VT
    WHERE VT.VEHICLE_TYPE_ID = V.VEHICLE_TYPE_ID
);

ALTER TABLE VEHICLE MODIFY (VEHICLE_TYPE_ID_NUM NOT NULL);

ALTER TABLE VEHICLE_TYPE DROP CONSTRAINT PK_VEHICLE_TYPE;

DROP INDEX IX_VEHICLE_TYPE;

ALTER TABLE VEHICLE_TYPE DROP COLUMN VEHICLE_TYPE_ID;
ALTER TABLE VEHICLE DROP COLUMN VEHICLE_TYPE_ID;

ALTER TABLE VEHICLE_TYPE RENAME COLUMN VEHICLE_TYPE_ID_NUM TO VEHICLE_TYPE_ID;
ALTER TABLE VEHICLE RENAME COLUMN VEHICLE_TYPE_ID_NUM TO VEHICLE_TYPE_ID;

ALTER TABLE VEHICLE_TYPE ADD CONSTRAINT PK_VEHICLE_TYPE
    PRIMARY KEY (VEHICLE_TYPE_ID);

ALTER TABLE VEHICLE ADD CONSTRAINT FK_VEHICLE_TYPE
    FOREIGN KEY (VEHICLE_TYPE_ID)
    REFERENCES VEHICLE_TYPE (VEHICLE_TYPE_ID);

CREATE INDEX IX_VEHICLE_TYPE ON VEHICLE (VEHICLE_TYPE_ID);

COMMIT;
