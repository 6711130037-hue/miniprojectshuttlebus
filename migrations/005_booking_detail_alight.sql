-- เก็บเวลาลง + จุดที่ลงไว้ที่จอง เพื่อให้แถว “สมชาย · #77 · 4 ที่นั่ง [ยืนยันลงแล้ว] ↓ กดแล้ว / ลงแล้ว ✓ (21:47)” ตรงกัน
ALTER TABLE BOOKING_DETAIL ADD (
    ALIGHTED_AT            TIMESTAMP(6),
    ALIGHTED_ROUTE_STOP_ID NUMBER(10)
);

ALTER TABLE BOOKING_DETAIL ADD CONSTRAINT CK_BD_ALIGHT_PAIR CHECK (
    (ALIGHTED_AT IS NULL AND ALIGHTED_ROUTE_STOP_ID IS NULL)
    OR
    (ALIGHTED_AT IS NOT NULL AND ALIGHTED_ROUTE_STOP_ID IS NOT NULL)
);

ALTER TABLE BOOKING_DETAIL ADD CONSTRAINT CK_BD_ALIGHT_AFTER_CHECKIN CHECK (
    ALIGHTED_AT IS NULL OR CHECKED_IN_AT IS NULL OR ALIGHTED_AT >= CHECKED_IN_AT
);

ALTER TABLE BOOKING_DETAIL ADD CONSTRAINT FK_BD_ALIGHT_RS FOREIGN KEY (ROUTE_ID, ALIGHTED_ROUTE_STOP_ID)
    REFERENCES ROUTE_STOP (ROUTE_ID, ROUTE_STOP_ID);

COMMIT;
