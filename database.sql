-- Keep ROUTE.TOTAL_TIME synchronized with the sum of its stop-to-stop times.
CREATE OR REPLACE TRIGGER TRG_RS_SYNC_ROUTE_TOTAL
FOR INSERT OR UPDATE OR DELETE ON ROUTE_STOP
COMPOUND TRIGGER
    TYPE ROUTE_ID_LIST IS TABLE OF ROUTE.ROUTE_ID%TYPE INDEX BY PLS_INTEGER;
    CHANGED_ROUTE_IDS ROUTE_ID_LIST;
    CHANGED_COUNT PLS_INTEGER := 0;

    PROCEDURE REMEMBER_ROUTE(P_ROUTE_ID ROUTE.ROUTE_ID%TYPE) IS
    BEGIN
        IF P_ROUTE_ID IS NOT NULL THEN
            CHANGED_COUNT := CHANGED_COUNT + 1;
            CHANGED_ROUTE_IDS(CHANGED_COUNT) := P_ROUTE_ID;
        END IF;
    END REMEMBER_ROUTE;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING THEN
            REMEMBER_ROUTE(:NEW.ROUTE_ID);
        ELSIF DELETING THEN
            REMEMBER_ROUTE(:OLD.ROUTE_ID);
        ELSE
            REMEMBER_ROUTE(:OLD.ROUTE_ID);
            REMEMBER_ROUTE(:NEW.ROUTE_ID);
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR I IN 1 .. CHANGED_COUNT LOOP
            UPDATE ROUTE R
            SET TOTAL_TIME = (
                SELECT NVL(SUM(RS.MINUTES_FROM_PREV), 0)
                FROM ROUTE_STOP RS
                WHERE RS.ROUTE_ID = CHANGED_ROUTE_IDS(I)
            )
            WHERE R.ROUTE_ID = CHANGED_ROUTE_IDS(I);
        END LOOP;
    END AFTER STATEMENT;
END;
